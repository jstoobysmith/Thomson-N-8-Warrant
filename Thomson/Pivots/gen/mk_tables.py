"""Turn the #eval output of `tables.lean` into `Thomson/Pivots/KT*.lean`.

    lake env lean Thomson/Pivots/gen/tables.lean > out.txt   # ~4 min in the interpreter
    python3 Thomson/Pivots/gen/mk_tables.py out.txt Thomson/Pivots

Each `decide +kernel` theorem is kept to a few thousand interval products, which is what the
kernel's cache can hold in about 1.5 GB: the blocks in chunks of three rows, the tensor one
`(p, q)` row at a time, the column one entry at a time.
"""
import sys, re, os

SC = os.path.dirname(os.path.abspath(__file__))
TOK = re.compile(r'⟨(-?\d+), (-?\d+)⟩')

def toks(s):
    return ['⟨%s, %s⟩' % m for m in TOK.findall(s)]

def mi_src(items):
    assert len(items) == 271, len(items)
    pos, blocks = 0, []
    for k in range(6):
        n = 9 - k
        rs = []
        for i in range(n):
            rs.append('[' + ', '.join(items[pos:pos + n]) + ']')
            pos += n
        blocks.append('[' + ',\n     '.join(rs) + ']')
    return '[' + ',\n    '.join(blocks) + ']'

def g_src(items):
    assert len(items) == 729, len(items)
    pos, blocks = 0, []
    for p in range(9):
        rs = []
        for q in range(9):
            rs.append('[' + ', '.join(items[pos:pos + 9]) + ']')
            pos += 9
        blocks.append('[' + ',\n     '.join(rs) + ']')
    return '[' + ',\n    '.join(blocks) + ']'

def col_src(items):
    assert len(items) == 24, len(items)
    return '[' + ',\n    '.join(items) + ']'

HDR = '-- GENERATED by Thomson/Pivots/gen/mk_tables.py; do not edit\n'
OPTS = 'set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n'

def tfile(idx, mi, g, col, tac):
    n = '%02d' % idx if idx < 24 else 'F'
    J = str(idx)
    isF = idx == 24
    HI = 'HI' if isF else f'(eHI {J})'
    ent = 'resAt' if isF else 'entAt'
    colname = 'resL' if isF else 'col' + n

    # --- the blocks, one (k, i) row at a time ---
    mis = ''
    for k in range(6):
        for i in range(9 - k):
            mis += (f'{OPTS}theorem MItab{n}_eq_{k}_{i} : ∀ j : Fin (9 - (({k} : Fin 6) : ℕ)),\n'
                    f'    mif MItab{n} {k} ⟨{i}, by omega⟩ j = MI BI {HI} {k} ⟨{i}, by omega⟩ j'
                    f' := by\n  {tac}\n\n')
    mi_all = (f'theorem MItab{n}_eq : ∀ (k : Fin 6) (i j : Fin (9 - (k : ℕ))),\n'
              f'    mif MItab{n} k i j = MI BI {HI} k i j := by\n'
              '  intro k i\n  fin_cases k <;> fin_cases i\n  exacts [' +
              ',\n    '.join(f'MItab{n}_eq_{k}_{i}' for k in range(6) for i in range(9 - k)) +
              ']\n')

    # --- the tensor, one (p, q) row at a time ---
    gs = ''
    for p in range(9):
        for q in range(9):
            gs += (f'{OPTS}theorem Gtab{n}_eq_{p}_{q} : ∀ r : Fin 9, '
                   f'getT Gtab{n} {p} {q} r = CF (mif MItab{n}) {p} {q} r := by\n  {tac}\n\n')
    gcases = ',\n    '.join(f'Gtab{n}_eq_{p}_{q}' for p in range(9) for q in range(9))
    g_all = (f'theorem Gtab{n}_eq : ∀ p q r : Fin 9, getT Gtab{n} p q r = CF (mif MItab{n}) p q r'
             ' := by\n  intro p q\n  fin_cases p <;> fin_cases q\n  exacts [' + gcases + ']\n')

    # --- the column, one entry at a time ---
    cs = ''.join(
        f'{OPTS}theorem {colname}_eq{i:02d} : {colname}.getD {i} Itv.zero '
        f'= {ent} (getT Gtab{n}) {i} := by\n  {tac}\n\n' for i in range(24))
    c_all = (f'theorem {colname}_eq : ∀ i : Fin 24, {colname}.getD (i : ℕ) Itv.zero '
             f'= {ent} (getT Gtab{n}) (i : ℕ) := by\n  intro i\n  fin_cases i\n  exacts [' +
             ',\n    '.join(f'{colname}_eq{i:02d}' for i in range(24)) + ']\n')

    if isF:
        mem = f'''theorem ITMem_Gtab{n} : ITMem (getT Gtab{n}) cFnum :=
  ITMem_getT_F MItab{n}_eq Gtab{n}_eq

theorem mem_{colname} (i : Fin 24) : ({colname}.getD (i : ℕ) Itv.zero).Mem (rowFun i pivotsNum) := by
  rw [{colname}_eq]; exact mem_resAt ITMem_Gtab{n} i'''
        what = 'the tensor of `F` at `pivotsNum`, and the residual'
        block = 'the pivot block `Hp pivotsNum`'
        last = 'the 24 entries of the residual'
    else:
        mem = f'''theorem ITMem_Gtab{n} : ITMem (getT Gtab{n}) (cG {J}) :=
  ITMem_getT_G MItab{n}_eq Gtab{n}_eq

theorem mem_{colname} (i : Fin 24) : ({colname}.getD (i : ℕ) Itv.zero).Mem (pivotMatrix i {J}) := by
  rw [{colname}_eq]; exact mem_entAt ITMem_Gtab{n} i'''
        what = f'the tensor of `Gh {J}`, and column {J}'
        block = f'the indicator block of pivot {J}'
        last = f'the 24 entries of column {J} of the pivot system'

    return f'''{HDR}import Thomson.Pivots.KBase

/-! # Task 1b: {what} — GENERATED

Three literal tables, each checked against its definition by `decide +kernel` in pieces small
enough for the kernel's cache (see `KBase`): the blocks `M_k = B_k H_k B_kᵀ` of {block},
three rows at a time; the coefficient tensor built from those blocks, one `(p, q)` row of nine
at a time; and {last}, one at a time. -/

namespace Thomson.Task1b

open Thomson Thomson.Tri5b

/-- The blocks `M_k`. -/
def MItab{n} : ITab :=
  {mi}

{mis}{mi_all}
/-- The coefficient tensor. -/
def Gtab{n} : ITab :=
  {g}

{gs}{g_all}
/-- The 24 entries. -/
def {colname} : List Itv :=
  {col}

{cs}{c_all}
{mem}

end Thomson.Task1b
'''

def main():
    src, outdir = sys.argv[1], sys.argv[2]
    tac = sys.argv[3] if len(sys.argv) > 3 else 'decide +kernel'
    mi, g, col, res = {}, {}, {}, None
    for line in open(src):
        if line.startswith('MI '):
            _, j, rest = line.split(' ', 2); mi[int(j)] = toks(rest)
        elif line.startswith('G '):
            _, j, rest = line.split(' ', 2); g[int(j)] = toks(rest)
        elif line.startswith('COL '):
            _, j, rest = line.split(' ', 2); col[int(j)] = toks(rest)
        elif line.startswith('RES '):
            res = toks(line.split(' ', 1)[1])
    col[24] = res
    for idx in range(25):
        nm = '%02d' % idx if idx < 24 else 'F'
        open(os.path.join(outdir, f'KT{nm}.lean'), 'w').write(
            tfile(idx, mi_src(mi[idx]), g_src(g[idx]), col_src(col[idx]), tac))
    print('written', outdir)

main()
