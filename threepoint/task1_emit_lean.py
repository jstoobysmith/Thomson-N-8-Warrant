"""Render the Task 1 data tables (scaled inverse-free kernel bases, fixed rationals, pivot slots,
numerical pivot values, row list) as Lean text: ../Thomson/ThreePoint/CertData.lean"""
import json, os, re, sys
from fractions import Fraction as Fr
import sympy as sp
here=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(here,'task1_design.json')))
u=sp.symbols('u')
def rat(q):
    q=Fr(q); return f"({q.numerator}/{q.denominator} : ℝ)" if q.denominator!=1 else f"({q.numerator} : ℝ)"
def poly(expr_str):
    P=sp.Poly(sp.expand(sp.sympify(expr_str)),u); terms=[]
    for (j,),c in sorted(P.terms()):
        c=sp.Rational(c); cs=rat(Fr(int(c.p),int(c.q)))
        terms.append(cs if j==0 else (f"{cs} * uStar" if j==1 else f"{cs} * uStar ^ {j}"))
    return " + ".join(terms) if terms else "(0 : ℝ)"
out=[]
out.append("""import Thomson.ThreePoint.Toolkit

/-! # The certificate data (Task 1, implicit form) — GENERATED by `threepoint/task1_emit_lean.py`
from `threepoint/task1_design.json` (`task1_design2.py`).  Do not edit by hand.

The data are: the scaled inverse-free bases `B k` of `v_k^⊥` (polynomials in `uStar`), the fixed
rational unknowns (`a0Fix`, `a1Fix`, `lamFix`, `Hfix`), the 24 pivot slots, the 24 definitional
tightness rows, and 22-digit reference values of the pivots.  See `Thomson.ThreePoint.Linear` for
the definitions built on these tables and `Thomson.ThreePoint.Tasks` for what remains to prove. -/

namespace Thomson

/-- Entry `(i, a)` of the basis matrix `B k` of `v_k^⊥` (column `a`, `a ≤ 7 − k`; column `8 − k`
is zero).  Column `a` is `c_a · (d_i e_i − n_i e_{p₀})` where `v_k = (n_i/d_i)_i` is the exact kernel
vector (`threepoint/kernel_vectors_exact.json`, `v_{p₀} = 1`) and `c_a` a rational scale making the
column have norm ≈ 1 at `u*`. -/
noncomputable def Bpoly : ℕ → ℕ → ℕ → ℝ""")
cases=[]
for k in range(6):
    for a,c in enumerate(D['basis'][str(k)]):
        sc=Fr(D['scales'][str(k)][a])
        cases.append(f"  | {k}, {c['i']}, {a} => {rat(sc)} * ({poly(c['den'])})")
        if sp.expand(sp.sympify(c['num']))!=0:
            cases.append(f"  | {k}, {c['p0']}, {a} => -{rat(sc)} * ({poly(c['num'])})")
out+=cases; out.append("  | _, _, _ => 0\n")
out.append("""/-- The basis matrices, square of size `9 − k` (last column zero). -/
noncomputable def B (k : Fin 6) : Matrix (Fin (9 - (k : ℕ))) (Fin (9 - (k : ℕ))) ℝ :=
  Matrix.of fun i a => Bpoly k i a
""")
free=D['free']
out.append(f"/-- The fixed rational unknowns. -/\nnoncomputable def a0Fix : ℝ := {rat(free['a0'])}\nnoncomputable def a1Fix : ℝ := {rat(free['a1'])}\nnoncomputable def lamFix : ℝ := {rat(free['lam'])}\n")
out.append("""/-- Fixed entries `H'_k[a,b]` (`a ≤ b`) of the symmetric blocks; the 24 pivot slots (`slot`) are
absent here (they are the unknowns solved for in `Thomson.ThreePoint.Linear`). -/
noncomputable def HfixTable : ℕ → ℕ → ℕ → ℝ""")
pat=re.compile(r"H(\d)\[(\d),(\d)\]")
for name,val in free.items():
    m=pat.match(name)
    if m: out.append(f"  | {m.group(1)}, {m.group(2)}, {m.group(3)} => {rat(val)}")
out.append("  | _, _, _ => 0\n")
out.append("""/-- Symmetrised fixed entries. -/
noncomputable def Hfix (k a b : ℕ) : ℝ := if a ≤ b then HfixTable k a b else HfixTable k b a
""")
slots=[pat.match(n).groups() for n in D['pivot_names']]
out.append("/-- The 24 pivot unknowns, as `(k, a, b)` with `a ≤ b`: the entries `H'_k[a,b] = H'_k[b,a]`. -/\ndef slot : Fin 24 → ℕ × ℕ × ℕ :=\n  ![" + ", ".join(f"({k}, {a}, {b})" for k,a,b in slots) + "]\n")
out.append("/-- Indicator of pivot `j` at position `(k, a, b)` (symmetric). -/\nnoncomputable def eH (j : Fin 24) (k a b : ℕ) : ℝ :=\n  if slot j = (k, a, b) ∨ slot j = (k, b, a) then 1 else 0\n")
pn=D['pivots_num']
out.append("/-- 22-digit reference values of the pivots (the exact pivots differ by `< 10⁻²¹`; used only\nin the enclosure Task 1b). -/\nnoncomputable def pivotsNum : Fin 24 → ℝ :=\n  ![" + ",\n    ".join(rat(pn[n]) for n in D['pivot_names']) + "]\n")
out.append("/-- The 24 definitional rows, in order (see `rowSpec`): " + ", ".join(D['rsel_labels']) + ".\nDropped (redundant, Task 1c): " + ", ".join(D['dropped']) + ". -/\ntheorem rowList_doc : True := trivial\n")
out.append("end Thomson\n")
txt="\n".join(out)
open(os.path.join(here,'..','Thomson','ThreePoint','CertData.lean'),'w').write(txt)
print(len(txt),"chars;", len(cases),"basis entries;", sum(1 for n in free if pat.match(n)),"fixed H entries; rows:",D['rsel_labels'])
