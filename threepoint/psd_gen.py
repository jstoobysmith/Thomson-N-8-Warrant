"""[Task 2] Data for `Thomson/PSD/`: an LDL^T factor of each block of the certificate, and an exact
Python mirror of the Lean check `Thomson.PSD.blockOK`.

For block `k` (size `n = 9 - k`), `A = Hp pivotsNum k` is an exact rational matrix whose last row and
column vanish.  With `mu = lambda_min / 2`, the LDL^T factorisation of `A - mu P` (`P` = identity on the
first `n - 1` coordinates) is computed exactly and rounded to the fixed-point grid `10^-40`.  Lean
then checks, in interval arithmetic, that `N = Hp p k - L D L^T` is diagonally dominant for every
`p` within `10^-12` of `pivotsNum` (the widening of `Thomson.Tri5b.HIe`); `N ~ mu P` up to `10^-12`.

Usage (from the repository root):  python3 threepoint/psd_gen.py
"""
import os, sys
from fractions import Fraction as Fr
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "threepoint"))
from pair_gen import S, HIe, HFIX, PIV, SLOT, add, sub, mul, cst, ZERO, sumL

HDR = "-- GENERATED by threepoint/psd_gen.py; do not edit\n"


def Aexact(k):
    n = 9 - k
    A = [[Fr(HFIX[k][a][b]) for b in range(n)] for a in range(n)]
    for j, (kk, a, b) in enumerate(SLOT):
        if kk == k:
            A[a][b] += PIV[j]
            if a != b:
                A[b][a] += PIV[j]
    return A


def ldl(M):
    n = len(M)
    L = [[Fr(0)] * n for _ in range(n)]
    d = [Fr(0)] * n
    for j in range(n):
        d[j] = M[j][j] - sum(L[j][r] ** 2 * d[r] for r in range(j))
        L[j][j] = Fr(1)
        for i in range(j + 1, n):
            L[i][j] = (M[i][j] - sum(L[i][r] * L[j][r] * d[r] for r in range(j))) / d[j] if d[j] else Fr(0)
    return L, d


def fx(q):
    return (q.numerator * S) // q.denominator


def absHi(I): return max(I[1], -I[0])


def NI(k, Lz, dz, a, b):
    n = 9 - k
    return sub(HIe(k, a, b), sumL([mul(mul(cst(Lz[a][r]), cst(dz[r])), cst(Lz[b][r])) for r in range(n)]))


def block_ok(k, Lz, dz):
    n = 9 - k
    ok = all(v >= 0 for v in dz)
    margins = []
    for a in range(n):
        row = [NI(k, Lz, dz, a, b) for b in range(n)]
        s = sum(absHi(I) for I in row)
        margins.append((2 * row[a][0] - s) / S)
        ok = ok and s <= 2 * row[a][0]
    return ok, margins


def build(k):
    n = 9 - k
    A = Aexact(k)
    assert all(A[n - 1][b] == 0 and A[b][n - 1] == 0 for b in range(n))
    lam = min(np.linalg.eigvalsh(np.array([[float(x) for x in r[:n - 1]] for r in A[:n - 1]])))
    mu = Fr(lam / 2).limit_denominator(10 ** 8)
    M = [[A[a][b] - (mu if a == b and a < n - 1 else 0) for b in range(n)] for a in range(n)]
    L, d = ldl(M)
    Lz = [[fx(L[a][r]) for r in range(n)] for a in range(n)]
    dz = [fx(x) for x in d]
    return lam, mu, Lz, dz


BLOCK = HDR + """import Thomson.PSD.Check

/-! # Task 2: the block `k = {k}` — GENERATED

`λ_min = {lam:.4e}`; `L`, `D` are the `LDLᵀ` factors of `A − {mu}·P`, on the grid `10⁻⁴⁰`. -/

namespace Thomson.PSD

set_option maxHeartbeats 4000000 in
def L{k} : List (List ℤ) := [
    {L}]

def d{k} : List ℤ := [{d}]

set_option maxRecDepth 100000 in
theorem ok{k} : blockOK {k} L{k} d{k} = true := by decide +kernel

end Thomson.PSD
"""


if __name__ == "__main__":
    out = os.path.join(ROOT, "Thomson", "PSD")
    os.makedirs(out, exist_ok=True)
    for k in range(6):
        lam, mu, Lz, dz = build(k)
        ok, margins = block_ok(k, Lz, dz)
        print(k, "lambda_min %.3e mu %s" % (lam, mu), ok, "min margin %.3e" % min(margins[:-1]))
        assert ok
        open(os.path.join(out, "Block%d.lean" % k), "w").write(BLOCK.format(
            k=k, lam=lam, mu=mu,
            L=",\n    ".join("[" + ", ".join(str(x) for x in row) + "]" for row in Lz),
            d=", ".join(str(x) for x in dz)))
